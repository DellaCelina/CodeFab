#pragma once

#include <string>

// [임시 구현] 누적된 입력 소스가 하나의 완결된 문장(들)으로 파싱을 시도할 준비가 되었는지 판단한다.
// - "(", "{", "[" 의 짝이 전부 맞으면 완결된 것으로 본다.
// - 큰따옴표 문자열 리터럴 내부의 괄호/중괄호는 집계하지 않는다.
// - 짝이 맞지 않게 닫히는 괄호(예: 여는 괄호 없이 "}")는 깊이를 0 밑으로 내리지 않는다.
//   (문법 오류 여부는 Assembler Unit이 판단하므로, 여기서는 "더 입력이 필요한가"만 판단한다.)
//
// 이 함수가 하는 일(괄호 매칭, 문자열 리터럴 인식)은 feature/tokenizer 브랜치의 Tokenizer가
// 소스를 스캔하면서 이미 수행하는 것과 본질적으로 중복이다. 따로 두 번 파싱하는 대신,
// 장기적으로는 Tokenizer의 스캐닝 결과(예: 미종결 문자열/괄호를 만났을 때 구분된 신호를 던지는 방식)로
// "입력 완결성 판단" 자체를 대체하는 것이 바람직하다.
//
// TODO(tokenizer 병합 후 refactor): 후보 방향 두 가지.
//   1) Tokenizer가 미종결 상태를 별도 예외/신호로 알리도록 하고, RunPromptShell이 Tokenize를
//      먼저 시도한 뒤 그 신호로 "더 입력이 필요한지"를 판단한다 (이 파일은 제거).
//   2) TokenizeInterface에 IsComplete(source) 같은 메서드를 추가해 위임한다.
// 어느 쪽이든 Tokenizer/Assembler 담당자와 인터페이스 합의가 필요하므로,
// 지금은 기존 동작을 그대로 유지하고 로직을 이 파일에 격리해 교체 지점을 명확히 해둔다.
bool IsInputComplete(const std::string& source);
